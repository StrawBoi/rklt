export const DotMatrixIcon: React.FC<DotMatrixIconProps> = ({
  type,
  size = 48,
  className = "",
  accent = false,
}) => {
  const pattern = MATRIX_PATTERNS[type] || MATRIX_PATTERNS.air;
  const rows = pattern.length;
  const cols = pattern[0].length;
  const dotPitch = 100 / Math.max(rows, cols);
  const dotRadius = dotPitch * 0.32;

  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 100 100"
      className={`dot-matrix-icon ${className}`}
      aria-hidden="true"
    >
      {pattern.map((row, r) =>
        row.split("").map((cell, c) => {
          const isActive = cell === "1";
          const cx = (c + 0.5) * dotPitch;
          const cy = (r + 0.5) * dotPitch;

          return (
            <circle
              key={`${r}-${c}`}
              cx={cx}
              cy={cy}
              r={isActive ? dotRadius : dotRadius * 0.65}
              fill={
                isActive
                  ? accent
                    ? "var(--brass-400)"
                    : "#ffffff"
                  : "rgba(255, 255, 255, 0.12)"
              }
              className={isActive ? "dot-active" : "dot-inactive"}
            />
          );
        })
      )}
    </svg>
  );
};
